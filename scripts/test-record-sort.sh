#!/usr/bin/env bash
set -euo pipefail

task_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$task_root"
source scripts/oxide-env.sh
readonly cccl_revision=571f2fc3bc53cd710e306ad43d58995c1fe4219f
cccl_root="${CCCL_ROOT:-$task_root/target/cccl-reference-$cccl_revision}"
if [[ ! -d "$cccl_root/.git" ]] || [[ "$(git -C "$cccl_root" rev-parse HEAD)" != "$cccl_revision" ]]; then
  printf '%s\n' "record sort reference requires pinned CCCL $cccl_revision" >&2
  exit 1
fi
while read -r digest path; do
  printf '%s  %s\n' "$digest" "$cccl_root/$path" | sha256sum --check --status
done <<'HASHES'
d0fd1ca25c0f3be6ed7726bf04d97ffd8c7cbe77372c08f94ed350f4c3101f75 cub/cub/device/device_merge_sort.cuh
e2634fc63822ba8c6331f90cdad80961c5a0c775afcac79b4b6d0fdd89fb4c5d thrust/thrust/system/cuda/detail/sort.h
HASHES

compute_sanitizer="$CUDA_TOOLKIT_PATH/compute-sanitizer/compute-sanitizer"
ptxas="$CUDA_HOME/bin/ptxas"
nvdisasm="$CUDA_HOME/bin/nvdisasm"
nvcc="$CUDA_HOME/bin/nvcc"
for tool in "$compute_sanitizer" "$ptxas" "$nvdisasm" "$nvcc"; do
  [[ -x "$tool" ]] || { printf '%s\n' "required CUDA tool unavailable: $tool" >&2; exit 1; }
done
build_dir="$(mktemp -d "${TMPDIR:-/tmp}/rccl-record-sort.XXXXXX")"
cleanup() {
  rm -rf -- "$build_dir"
  rm -f -- record_sort.options record_sort.target record_sort_benchmark.options record_sort_benchmark.target
}
trap cleanup EXIT
arch="${RCCL_ARCH:-sm_89}"

cargo test -p rccl-thrust record_sort::tests
cargo test -p rccl-thrust api_tests
cargo oxide build --arch "$arch" --features cuda-oxide-example -- \
  --release --package rccl-thrust --example record_sort
./target/release/examples/record_sort
"$compute_sanitizer" --tool memcheck --error-exitcode 97 ./target/release/examples/record_sort
"$compute_sanitizer" --tool racecheck --error-exitcode 98 ./target/release/examples/record_sort
"$compute_sanitizer" --tool synccheck --error-exitcode 99 ./target/release/examples/record_sort
./target/release/examples/record_sort --fault >"$build_dir/fault.stdout" 2>"$build_dir/fault.stderr"
if ! rg -q 'record sort comparator fault surfaced:' "$build_dir/fault.stderr"; then
  printf '%s\n' 'injected record comparator fault did not surface at completion' >&2
  exit 1
fi

"$nvcc" -std=c++20 -O3 -arch="$arch" \
  -I "$cccl_root/cub" -I "$cccl_root/thrust" -I "$cccl_root/libcudacxx/include" \
  benchmarks/cub-record-sort-reference.cu -o "$build_dir/cub-record-sort-reference"
"$build_dir/cub-record-sort-reference"
"$nvcc" -std=c++20 -O3 -arch="$arch" -cubin -Xptxas=-v \
  -I "$cccl_root/cub" -I "$cccl_root/thrust" -I "$cccl_root/libcudacxx/include" \
  benchmarks/cub-record-sort-resource-reference.cu \
  -o "$build_dir/cub-row6-resource.cubin" 2>"$build_dir/cub-row6-resources.txt"
"$nvdisasm" "$build_dir/cub-row6-resource.cubin" >"$build_dir/cub-row6-resource.sass"
if rg -n '[1-9][0-9]* bytes spill (stores|loads)' "$build_dir/cub-row6-resources.txt"; then
  printf '%s\n' 'pinned CUB Row<6> resource oracle unexpectedly spills' >&2
  exit 1
fi
if rg -n '(^|[[:space:]])(?:LDL|STL)(?:\.|[[:space:]])' "$build_dir/cub-row6-resource.sass"; then
  printf '%s\n' 'pinned CUB Row<6> resource oracle unexpectedly uses local memory' >&2
  exit 1
fi

python3 - target/release/examples/record_sort "$build_dir/ordering-module.ptx" <<'PY'
import pathlib, sys
image = pathlib.Path(sys.argv[1]).read_bytes()
marker = b"// Generated by LLVM NVPTX Back-End"
pos = 0
while True:
    start = image.find(marker, pos)
    if start < 0: raise SystemExit("embedded record-sort PTX module not found")
    end = image.find(b"\0", start)
    if end < 0: raise SystemExit("unterminated embedded PTX module")
    module = image[start:end]
    if b"device_merge_sort_block_pairs_256" in module and b"device_merge_sort_partition" in module:
        pathlib.Path(sys.argv[2]).write_bytes(module)
        break
    pos = end + 1
PY
python3 - "$build_dir/ordering-module.ptx" "$build_dir/record-hot.ptx" <<'PY'
import pathlib, re, sys
text = pathlib.Path(sys.argv[1]).read_text()
first = text.find(".visible .entry")
if first < 0: raise SystemExit("ordering PTX has no entries")
prefix = text[:first]
entries = re.findall(
    r"(?ms)^\.visible \.entry (?:device_merge_sort_block_(?:keys|pairs)(?:_in_place)?_256|device_merge_sort_partition|device_merge_sort_merge_(?:keys|pairs)_256)[^\n]*\n.*?^\}\s*$",
    text,
)
if not entries: raise SystemExit("instantiated record-sort entries not found")
pathlib.Path(sys.argv[2]).write_text(prefix + "\n".join(entries))
PY
python3 - "$build_dir/ordering-module.ptx" "$build_dir/row6-entries.txt" <<'PY'
import pathlib, re, sys
text = pathlib.Path(sys.argv[1]).read_text()
entries = re.findall(
    r"(?ms)^\.visible \.entry (device_merge_sort_[^\n(]+)\([^\n]*\n(.*?^\}\s*$)",
    text,
)
names = [
    name for name, body in entries
    if re.search(r"(?:mad\.lo\.s64|mul\.lo\.s64|mul\.wide\.u32)[^\n]*,\s*24,\s*", body)
]
required = (
    "device_merge_sort_block_keys_in_place_256",
    "device_merge_sort_block_keys_256",
    "device_merge_sort_partition",
    "device_merge_sort_merge_keys_256",
)
for prefix in required:
    if not any(name.startswith(prefix) for name in names):
        raise SystemExit(f"missing Row<6> resource entry: {prefix}")
pathlib.Path(sys.argv[2]).write_text("\n".join(names) + "\n")
PY
for entry in device_merge_sort_block_keys_256 device_merge_sort_block_pairs_256 device_merge_sort_partition device_merge_sort_merge_keys_256 device_merge_sort_merge_pairs_256; do
  rg -q "\.entry $entry" "$build_dir/record-hot.ptx" || { printf '%s\n' "missing PTX entry: $entry" >&2; exit 1; }
done
if ! rg -q '\.reqntid 256, 1, 1' "$build_dir/record-hot.ptx" \
  || ! rg -q '(^|[[:space:]])ld\.' "$build_dir/record-hot.ptx" \
  || ! rg -q '(^|[[:space:]])st\.' "$build_dir/record-hot.ptx"; then
  printf '%s\n' 'record-sort PTX lost fixed launch or direct typed accesses' >&2
  exit 1
fi
if rg -n '(^|[[:space:]])atom\.' "$build_dir/record-hot.ptx"; then
  printf '%s\n' 'record-sort PTX contains global atomics' >&2
  exit 1
fi
"$ptxas" -v -arch="$arch" "$build_dir/record-hot.ptx" -o "$build_dir/record-hot.cubin" 2>"$build_dir/resources.txt"
if rg -n '[1-9][0-9]* bytes spill (stores|loads)' "$build_dir/resources.txt"; then
  printf '%s\n' 'record-sort production or fault entry contains a register spill' >&2
  exit 1
fi
"$nvdisasm" "$build_dir/record-hot.cubin" >"$build_dir/record-hot.sass"
if ! rg -q 'LDG\.E|LD\.E' "$build_dir/record-hot.sass" || ! rg -q 'STG\.E|ST\.E' "$build_dir/record-hot.sass"; then
  printf '%s\n' 'record-sort SASS lost global loads or stores' >&2
  exit 1
fi
if rg -n 'ATOM' "$build_dir/record-hot.sass"; then
  printf '%s\n' 'record-sort SASS contains atomics' >&2
  exit 1
fi
printf '%s\n' 'Rust Row<6> entries (24-byte stride):'
cat "$build_dir/row6-entries.txt"
printf '%s\n' 'Rust record-sort resources:'
rg 'device_merge_sort_|Used [0-9]+ registers|stack frame|spill' "$build_dir/resources.txt" || true
printf '%s\n' 'Pinned CUB Row<6> resources:'
rg 'Row6|Used [0-9]+ registers|stack frame|spill' "$build_dir/cub-row6-resources.txt" || true
printf '%s\n' 'Stable lexicographic record sort correctness, contracts, fault, SM89, sanitizers, pinned CUB differential, and spill/resource audit: PASS'
