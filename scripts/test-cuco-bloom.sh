#!/usr/bin/env bash
set -euo pipefail

task_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$task_root"
source scripts/oxide-env.sh

readonly cuco_revision=1d538b6befc286ab450d9e27d7ffbc4f1415c641
readonly cccl_revision=571f2fc3bc53cd710e306ad43d58995c1fe4219f
cuco_root="${CUCO_ROOT:-$task_root/target/cuco-reference-$cuco_revision}"
cccl_root="${CCCL_ROOT:-$task_root/target/cccl-reference-$cccl_revision}"

checkout_pinned() {
  local root="$1" origin="$2" revision="$3" label="$4"
  if [[ ! -d "$root/.git" ]]; then
    mkdir -p "$task_root/target"
    local staging
    staging="$(mktemp -d "$task_root/target/.${label}.XXXXXX")"
    git -C "$staging" init --quiet
    git -C "$staging" remote add origin "$origin"
    git -C "$staging" fetch --quiet --depth 1 origin "$revision"
    git -C "$staging" checkout --quiet --detach FETCH_HEAD
    mv "$staging" "$root"
  fi
  if [[ "$(git -C "$root" rev-parse HEAD)" != "$revision" ]]; then
    printf '%s\n' "$label must resolve to pinned revision $revision" >&2
    exit 1
  fi
}
checkout_pinned "$cuco_root" https://github.com/NVIDIA/cuCollections.git "$cuco_revision" cuco
checkout_pinned "$cccl_root" https://github.com/NVIDIA/cccl.git "$cccl_revision" cccl

nvcc="$CUDA_HOME/bin/nvcc"
compute_sanitizer="$CUDA_TOOLKIT_PATH/compute-sanitizer/compute-sanitizer"
ptxas="$CUDA_HOME/bin/ptxas"
nvdisasm="$CUDA_HOME/bin/nvdisasm"
for tool in "$nvcc" "$compute_sanitizer" "$ptxas" "$nvdisasm"; do
  [[ -x "$tool" ]] || { printf '%s\n' "required CUDA tool unavailable: $tool" >&2; exit 1; }
done

build_dir="$(mktemp -d "${TMPDIR:-/tmp}/rccl-cuco-bloom.XXXXXX")"
cleanup() { rm -rf -- "$build_dir"; }
trap cleanup EXIT

cargo test -p rccl-cuco bloom::tests
cargo oxide build --arch "${RCCL_ARCH:-sm_89}" --features cuda-oxide-example -- \
  --package rccl-cuco --example bloom
./target/debug/examples/bloom
"$compute_sanitizer" --tool memcheck --error-exitcode 97 ./target/debug/examples/bloom
"$compute_sanitizer" --tool racecheck --error-exitcode 98 ./target/debug/examples/bloom
"$compute_sanitizer" --tool synccheck --error-exitcode 99 ./target/debug/examples/bloom

cargo oxide build --arch "${RCCL_ARCH:-sm_89}" --features cuda-oxide-example -- \
  --release --package rccl-cuco --example bloom_benchmark
python3 - target/release/examples/bloom_benchmark "$build_dir/bloom-module.ptx" <<'PY'
import pathlib
import sys

image = pathlib.Path(sys.argv[1]).read_bytes()
start = image.index(b"// Generated by LLVM NVPTX Back-End")
end = image.index(b"\0", start)
pathlib.Path(sys.argv[2]).write_bytes(image[start:end])
PY
awk '
    !done && /\.visible \.entry bloom_add_TID_/ { capture=1; found=1 }
    capture { print }
    capture && /-- End function/ { capture=0; done=1 }
    END { if (!found || !done) exit 1 }
  ' "$build_dir/bloom-module.ptx" > "$build_dir/bloom-add.ptx"
awk '
    !done && /\.visible \.entry bloom_contains_TID_/ { capture=1; found=1 }
    capture { print }
    capture && /-- End function/ { capture=0; done=1 }
    END { if (!found || !done) exit 1 }
  ' "$build_dir/bloom-module.ptx" > "$build_dir/bloom-contains.ptx"
if ! rg -q '\.reqntid 256, 1, 1' "$build_dir/bloom-add.ptx" \
  || ! rg -q '(atom|red)\.relaxed\.gpu\.global\.or\.b32' "$build_dir/bloom-add.ptx" \
  || ! rg -q 'mul\.(wide\.)?u32' "$build_dir/bloom-add.ptx" \
  || ! rg -q 'shr\.u(32|64)' "$build_dir/bloom-add.ptx" \
  || ! rg -q '\.reqntid 256, 1, 1' "$build_dir/bloom-contains.ptx" \
  || ! rg -q 'mul\.(wide\.)?u32' "$build_dir/bloom-contains.ptx"; then
  printf '%s\n' 'Bloom PTX lost device-scope OR publication, multiply-shift block/bit addressing, or 256-thread launch shape' >&2
  exit 1
fi
contains_loads="$(rg -c '\bld\.global\.b64\b' "$build_dir/bloom-contains.ptx")"
if [[ "$contains_loads" != 5 ]] || rg -q '\bld\.global\.b32\b' "$build_dir/bloom-contains.ptx"; then
  printf '%s\n' "Bloom contains must keep its key plus four paired word loads (found $contains_loads 64-bit loads)" >&2
  exit 1
fi
if rg -n '(atom|red)\..*\.sys|membar|[ls]t?\.local|\bcall\b|\.visible \.func' \
  "$build_dir/bloom-add.ptx" "$build_dir/bloom-contains.ptx"; then
  printf '%s\n' 'Bloom hot path contains a system atomic, fence, local spill, or helper call' >&2
  exit 1
fi
"$ptxas" -arch="${RCCL_ARCH:-sm_89}" "$build_dir/bloom-module.ptx" -o "$build_dir/bloom.cubin"
"$nvdisasm" "$build_dir/bloom.cubin" > "$build_dir/bloom.sass"
if ! rg -q '(RED|ATOM).*OR' "$build_dir/bloom.sass"; then
  printf '%s\n' 'Bloom SASS contains no atomic OR publication' >&2
  exit 1
fi
if rg -n 'LDL|STL' "$build_dir/bloom.sass"; then
  printf '%s\n' 'Bloom SASS contains local-memory traffic' >&2
  exit 1
fi

"$nvcc" -std=c++20 -O3 --expt-extended-lambda -arch="${RCCL_ARCH:-sm_89}" \
  -I"$cuco_root/include" -I"$cccl_root/cub" -I"$cccl_root/thrust" \
  -I"$cccl_root/libcudacxx/include" benchmarks/cuco-bloom-reference.cu \
  -o "$build_dir/cuco-bloom-reference"
reference="$($build_dir/cuco-bloom-reference --items 65536 --blocks 8192 --iterations 3)"
rust="$(target/release/examples/bloom_benchmark --items 65536 --blocks 8192 --iterations 3)"
reference_checksum="$(sed -n 's/.*checksum=\([0-9a-f]*\).*/\1/p' <<<"$reference")"
rust_checksum="$(sed -n 's/.*checksum=\([0-9a-f]*\).*/\1/p' <<<"$rust")"
if [[ -z "$reference_checksum" || "$reference_checksum" != "$rust_checksum" ]]; then
  printf '%s\n' "Bloom differential mismatch: cuCollections=$reference_checksum RCCL=$rust_checksum" >&2
  exit 1
fi
printf '%s\n' "$reference" "$rust"
printf '%s\n' 'Pinned HISA/cuCollections Bloom correctness, sanitizer, differential, and code-shape matrix: PASS'
