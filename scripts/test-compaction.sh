#!/usr/bin/env bash
set -euo pipefail

task_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$task_root"
source scripts/oxide-env.sh
readonly cccl_revision=571f2fc3bc53cd710e306ad43d58995c1fe4219f
cccl_root="${CCCL_ROOT:-$task_root/target/cccl-reference-$cccl_revision}"
if [[ ! -d "$cccl_root/.git" ]] || [[ "$(git -C "$cccl_root" rev-parse HEAD)" != "$cccl_revision" ]]; then
  printf '%s\n' "compaction reference requires pinned CCCL $cccl_revision" >&2
  exit 1
fi
while read -r digest path; do
  printf '%s  %s\n' "$digest" "$cccl_root/$path" | sha256sum --check --status
done <<'HASHES'
d3f76f1bdaa04358770809ab3eb9470f03d73f2ac332309f2d3c095b73adb086 cub/cub/device/device_scan.cuh
83d055d1e7a89fb877c6660ee1edb489666c55551a21e1d02b7a1a8da9c519da cub/cub/device/device_select.cuh
0b4e237e54de724cf14812b54ca32e585b3187bfafb8825f2719a76a37bf8034 thrust/thrust/system/cuda/detail/copy_if.h
7c606700e64a4297aa0c801e37a172402d4f95e9c2f50c1c70b8f895936ad4af thrust/thrust/system/cuda/detail/unique.h
b9532929de32cd27aa509adb3ca99a593888c0da76ef97c94a40960544ebbbda thrust/thrust/system/cuda/detail/partition.h
HASHES

compute_sanitizer="$CUDA_TOOLKIT_PATH/compute-sanitizer/compute-sanitizer"
ptxas="$CUDA_HOME/bin/ptxas"
nvdisasm="$CUDA_HOME/bin/nvdisasm"
nvcc="$CUDA_HOME/bin/nvcc"
for tool in "$compute_sanitizer" "$ptxas" "$nvdisasm" "$nvcc"; do
  [[ -x "$tool" ]] || { printf '%s\n' "required CUDA tool unavailable: $tool" >&2; exit 1; }
done
build_dir="$(mktemp -d "${TMPDIR:-/tmp}/rccl-compaction.XXXXXX")"
cleanup() {
  rm -rf -- "$build_dir"
  rm -f -- compaction.options compaction.target compaction_benchmark.options compaction_benchmark.target
}
trap cleanup EXIT
arch="${RCCL_ARCH:-sm_89}"

cargo test -p rccl-cub compaction::tests
cargo oxide build --arch "$arch" --features cuda-oxide-example -- \
  --release --package rccl-thrust --example compaction
./target/release/examples/compaction
"$compute_sanitizer" --tool memcheck --error-exitcode 97 ./target/release/examples/compaction
"$compute_sanitizer" --tool racecheck --error-exitcode 98 ./target/release/examples/compaction
"$compute_sanitizer" --tool synccheck --error-exitcode 99 ./target/release/examples/compaction
./target/release/examples/compaction --range-oob >"$build_dir/oob.stdout" 2>"$build_dir/oob.stderr"
if ! rg -q 'compaction range OOB surfaced:' "$build_dir/oob.stderr"; then
  printf '%s\n' 'composed-range OOB did not surface a CUDA execution fault' >&2
  exit 1
fi

"$nvcc" -std=c++17 -O3 -arch="$arch" \
  -I "$cccl_root/cub" -I "$cccl_root/thrust" -I "$cccl_root/libcudacxx/include" \
  benchmarks/cub-compaction-reference.cu -o "$build_dir/cub-compaction-reference"
"$build_dir/cub-compaction-reference"

python3 - target/release/examples/compaction "$build_dir/compaction-module.ptx" <<'PY'
import pathlib, sys
image = pathlib.Path(sys.argv[1]).read_bytes()
marker = b"// Generated by LLVM NVPTX Back-End"
pos = 0
while True:
    start = image.find(marker, pos)
    if start < 0: raise SystemExit("embedded compaction PTX module not found")
    end = image.find(b"\0", start)
    if end < 0: raise SystemExit("unterminated embedded PTX module")
    module = image[start:end]
    if b"mark_predicate" in module and b"scatter_partition" in module:
        pathlib.Path(sys.argv[2]).write_bytes(module)
        break
    pos = end + 1
PY
python3 - "$build_dir/compaction-module.ptx" "$build_dir/compaction-hot.ptx" <<'PY'
import pathlib, re, sys
text = pathlib.Path(sys.argv[1]).read_text()
entries = re.findall(r"(?ms)^\.visible \.entry (?:mark_predicate|mark_flagged|mark_adjacent_unique|scatter_selected|scatter_partition)[^\n]*\n.*?^\}\s*$", text)
if not entries: raise SystemExit("instantiated compaction entries not found")
pathlib.Path(sys.argv[2]).write_text("\n".join(entries))
PY
for entry in mark_predicate mark_flagged mark_adjacent_unique scatter_selected scatter_partition; do
  rg -q "\\.entry $entry" "$build_dir/compaction-hot.ptx" || { printf '%s\n' "missing PTX entry: $entry" >&2; exit 1; }
done
if ! rg -q '\.reqntid 256, 1, 1' "$build_dir/compaction-hot.ptx" \
  || ! rg -q '(^|[[:space:]])ld\.' "$build_dir/compaction-hot.ptx" \
  || ! rg -q '(^|[[:space:]])st\.' "$build_dir/compaction-hot.ptx"; then
  printf '%s\n' 'compaction PTX lost fixed launch or direct typed accesses' >&2
  exit 1
fi
if rg -n '(^|[[:space:]])(ld|st)\.local|(^|[[:space:]])call(\.|[[:space:]])|(^|[[:space:]])atom\.' "$build_dir/compaction-hot.ptx"; then
  printf '%s\n' 'compaction PTX contains local traffic, out-of-line calls, or global atomics' >&2
  exit 1
fi
"$ptxas" -v -arch="$arch" "$build_dir/compaction-module.ptx" -o "$build_dir/compaction.cubin" 2>"$build_dir/resources.txt"
"$nvdisasm" "$build_dir/compaction.cubin" >"$build_dir/compaction.sass"
if ! rg -q 'LDG\.E|LD\.E' "$build_dir/compaction.sass" || ! rg -q 'STG\.E|ST\.E' "$build_dir/compaction.sass"; then
  printf '%s\n' 'compaction SASS lost global loads or stores' >&2
  exit 1
fi
if rg -n 'LDL|STL|ATOM' "$build_dir/compaction.sass"; then
  printf '%s\n' 'compaction module contains local-memory traffic or atomics' >&2
  exit 1
fi
rg 'mark_predicate|mark_flagged|mark_adjacent_unique|scatter_selected|scatter_partition|Used [0-9]+ registers|spill' "$build_dir/resources.txt" || true
printf '%s\n' 'Select/flagged-select/adjacent-unique/stable-partition correctness, contracts, fault, SM89, sanitizers, pinned CUB differential, and resource audit: PASS'
