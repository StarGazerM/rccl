#!/usr/bin/env bash
set -euo pipefail

task_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$task_root"
source scripts/oxide-env.sh

readonly cccl_revision=571f2fc3bc53cd710e306ad43d58995c1fe4219f
cccl_root="${CCCL_ROOT:-$task_root/target/cccl-reference-$cccl_revision}"
if [[ ! -d "$cccl_root/.git" ]] || [[ "$(git -C "$cccl_root" rev-parse HEAD)" != "$cccl_revision" ]]; then
  printf '%s\n' "block scan reference requires pinned CCCL $cccl_revision" >&2
  exit 1
fi
printf '%s  %s\n' 9d3799e8e3e204873a78208a3df0ccb62bd53bcc56011c93e850d49dbb85be2e \
  "$cccl_root/cub/cub/block/block_scan.cuh" | sha256sum --check --status
printf '%s  %s\n' 2045175416e2eedfe89f8b56a677a250a238f67aa76893c18aced39fc774335e \
  "$cccl_root/cub/cub/block/specializations/block_scan_warp_scans.cuh" | sha256sum --check --status
printf '%s  %s\n' e3ec71e79270d9207242ed2e4317a5f8ceb5989ffdea7d2f357153fc539c002c \
  "$cccl_root/cub/test/catch2_test_block_scan.cu" | sha256sum --check --status
printf '%s  %s\n' ee482703b76d4b768eb13ef8ba077e0e15d168593f78dc1d66dd09a7bde91b1f \
  "$cccl_root/cub/examples/block/example_block_scan.cu" | sha256sum --check --status

compute_sanitizer="$CUDA_TOOLKIT_PATH/compute-sanitizer/compute-sanitizer"
ptxas="$CUDA_HOME/bin/ptxas"
nvdisasm="$CUDA_HOME/bin/nvdisasm"
nvcc="$CUDA_HOME/bin/nvcc"
for tool in "$compute_sanitizer" "$ptxas" "$nvdisasm" "$nvcc"; do
  [[ -x "$tool" ]] || { printf '%s\n' "required CUDA tool unavailable: $tool" >&2; exit 1; }
done

build_dir="$(mktemp -d "${TMPDIR:-/tmp}/rccl-block-scan.XXXXXX")"
cleanup() {
  rm -rf -- "$build_dir"
  rm -f -- device_scan.options device_scan.target block_scan_probe.options block_scan_probe.target
}
trap cleanup EXIT
arch="${RCCL_ARCH:-sm_89}"

cargo test -p rccl-cub scan::tests
for example in block_scan_probe; do
  cargo oxide build --arch "$arch" --features cuda-oxide-example -- \
    --release --package rccl-cub --example "$example"
done
cargo oxide build --arch "$arch" --features cuda-oxide-example -- \
  --release --package rccl-thrust --example device_scan

./target/release/examples/block_scan_probe
./target/release/examples/device_scan
"$compute_sanitizer" --tool memcheck --error-exitcode 97 \
  ./target/release/examples/device_scan
"$compute_sanitizer" --tool racecheck --error-exitcode 98 \
  ./target/release/examples/device_scan
"$compute_sanitizer" --tool synccheck --error-exitcode 99 \
  ./target/release/examples/device_scan
./target/release/examples/block_scan_probe --invalid-valid \
  >"$build_dir/fault.stdout" 2>"$build_dir/fault.stderr"
if ! rg -q 'invalid block-scan valid count surfaced:' "$build_dir/fault.stderr"; then
  printf '%s\n' 'block scan invalid logical extent did not surface a CUDA fault' >&2
  exit 1
fi

"$nvcc" -std=c++17 -O3 -arch="$arch" \
  -I "$cccl_root/cub" -I "$cccl_root/thrust" -I "$cccl_root/libcudacxx/include" \
  benchmarks/cub-block-scan-reference.cu -o "$build_dir/cub-block-scan-reference"
"$build_dir/cub-block-scan-reference"

python3 - target/release/examples/device_scan "$build_dir/scan-module.ptx" <<'PY'
import pathlib
import sys
image = pathlib.Path(sys.argv[1]).read_bytes()
marker = b"// Generated by LLVM NVPTX Back-End"
position = 0
while True:
    start = image.find(marker, position)
    if start < 0:
        raise SystemExit("embedded device scan PTX module not found")
    end = image.find(b"\0", start)
    if end < 0:
        raise SystemExit("unterminated embedded PTX module")
    module = image[start:end]
    if b"device_scan_tiles" in module:
        pathlib.Path(sys.argv[2]).write_bytes(module)
        break
    position = end + 1
PY
python3 - "$build_dir/scan-module.ptx" "$build_dir/scan-hot.ptx" <<'PY'
import pathlib
import re
import sys
text = pathlib.Path(sys.argv[1]).read_text()
entries = re.findall(r"(?ms)^\.visible \.entry device_scan_tiles[^\n]*\n.*?^\}\s*$", text)
if not entries:
    raise SystemExit("instantiated device_scan_tiles entries not found")
pathlib.Path(sys.argv[2]).write_text("\n".join(entries))
PY
if ! rg -q '\.reqntid 256, 1, 1' "$build_dir/scan-hot.ptx" \
  || ! rg -q 'shfl\.sync\.up\.b32' "$build_dir/scan-hot.ptx" \
  || ! rg -q 'bar\.sync[[:space:]]+0;' "$build_dir/scan-hot.ptx" \
  || ! rg -q '(^|[[:space:]])ld\.shared' "$build_dir/scan-hot.ptx" \
  || ! rg -q '(^|[[:space:]])st\.shared' "$build_dir/scan-hot.ptx"; then
  printf '%s\n' 'device scan PTX lost fixed block shape, shuffle scan, or CTA barriers' >&2
  exit 1
fi
if [[ "$(rg -c 'bar\.sync[[:space:]]+0;' "$build_dir/scan-hot.ptx")" -lt 6 ]]; then
  printf '%s\n' 'device scan PTX lost the two primitive barriers per specialization' >&2
  exit 1
fi
if rg -n '(^|[[:space:]])(ld|st)\.local|(^|[[:space:]])call(\.|[[:space:]])|(^|[[:space:]])atom\.' \
  "$build_dir/scan-hot.ptx"; then
  printf '%s\n' 'device scan hot PTX contains local traffic, out-of-line calls, or global atomics' >&2
  exit 1
fi
"$ptxas" -v -arch="$arch" "$build_dir/scan-module.ptx" \
  -o "$build_dir/scan.cubin" 2>"$build_dir/ptxas-resources.txt"
"$nvdisasm" "$build_dir/scan.cubin" >"$build_dir/scan.sass"
if ! rg -q 'SHFL\.UP' "$build_dir/scan.sass" || ! rg -q 'BAR\.SYNC' "$build_dir/scan.sass"; then
  printf '%s\n' 'device scan SASS lost shuffle scan or CTA barriers' >&2
  exit 1
fi
if rg -n 'LDL|STL' "$build_dir/scan.sass"; then
  printf '%s\n' 'device scan module contains SASS local-memory traffic' >&2
  exit 1
fi
rg 'device_scan_tiles|Used [0-9]+ registers|spill' "$build_dir/ptxas-resources.txt" || true

printf '%s\n' 'Private BlockScan and device scan correctness, boundaries, aggregate, fault, SM89, sanitizer, pinned CUB oracle, and resource audit: PASS'
