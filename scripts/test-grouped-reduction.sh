#!/usr/bin/env bash
set -euo pipefail

task_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$task_root"
source scripts/oxide-env.sh
readonly cccl_revision=571f2fc3bc53cd710e306ad43d58995c1fe4219f
cccl_root="${CCCL_ROOT:-$task_root/target/cccl-reference-$cccl_revision}"
if [[ ! -d "$cccl_root/.git" ]] || [[ "$(git -C "$cccl_root" rev-parse HEAD)" != "$cccl_revision" ]]; then
  printf '%s\n' "grouped reduction reference requires pinned CCCL $cccl_revision" >&2
  exit 1
fi
while read -r digest path; do
  printf '%s  %s\n' "$digest" "$cccl_root/$path" | sha256sum --check --status
done <<'HASHES'
d3f76f1bdaa04358770809ab3eb9470f03d73f2ac332309f2d3c095b73adb086 cub/cub/device/device_scan.cuh
16ebc9f81a33e34ed6641e8734b5a98bf6fe2bb2bc027f1fde487bbf512b94cf cub/cub/device/device_reduce.cuh
HASHES

compute_sanitizer="$CUDA_TOOLKIT_PATH/compute-sanitizer/compute-sanitizer"
ptxas="$CUDA_HOME/bin/ptxas"
nvdisasm="$CUDA_HOME/bin/nvdisasm"
nvcc="$CUDA_HOME/bin/nvcc"
for tool in "$compute_sanitizer" "$ptxas" "$nvdisasm" "$nvcc"; do
  [[ -x "$tool" ]] || { printf '%s\n' "required CUDA tool unavailable: $tool" >&2; exit 1; }
done
build_dir="$(mktemp -d "${TMPDIR:-/tmp}/rccl-grouped-reduction.XXXXXX")"
cleanup() {
  rm -rf -- "$build_dir"
  rm -f -- grouped_reduction.options grouped_reduction.target grouped_reduction_benchmark.options grouped_reduction_benchmark.target
}
trap cleanup EXIT
arch="${RCCL_ARCH:-sm_89}"

cargo check -p rccl-thrust
cargo oxide build --arch "$arch" --features cuda-oxide-example -- \
  --release --package rccl-thrust --example grouped_reduction
./target/release/examples/grouped_reduction
"$compute_sanitizer" --tool memcheck --error-exitcode 97 ./target/release/examples/grouped_reduction
"$compute_sanitizer" --tool racecheck --error-exitcode 98 ./target/release/examples/grouped_reduction
"$compute_sanitizer" --tool synccheck --error-exitcode 99 ./target/release/examples/grouped_reduction
./target/release/examples/grouped_reduction --range-oob >"$build_dir/oob.stdout" 2>"$build_dir/oob.stderr"
if ! rg -q 'grouped reduction range OOB surfaced:' "$build_dir/oob.stderr"; then
  printf '%s\n' 'composed-range OOB did not surface a CUDA execution fault' >&2
  exit 1
fi

"$nvcc" -std=c++17 -O3 -arch="$arch" \
  -I "$cccl_root/cub" -I "$cccl_root/thrust" -I "$cccl_root/libcudacxx/include" \
  benchmarks/cub-grouped-reduction-reference.cu -o "$build_dir/cub-grouped-reduction-reference"
"$build_dir/cub-grouped-reduction-reference"

python3 - target/release/examples/grouped_reduction "$build_dir/grouped-module.ptx" <<'PY'
import pathlib, sys
image = pathlib.Path(sys.argv[1]).read_bytes()
marker = b"// Generated by LLVM NVPTX Back-End"
pos = 0
while True:
    start = image.find(marker, pos)
    if start < 0: raise SystemExit("embedded grouped reduction PTX module not found")
    end = image.find(b"\0", start)
    if end < 0: raise SystemExit("unterminated embedded PTX module")
    module = image[start:end]
    if b"reduce_adjacent_groups" in module and b"mark_adjacent_unique" in module:
        pathlib.Path(sys.argv[2]).write_bytes(module)
        break
    pos = end + 1
PY
python3 - "$build_dir/grouped-module.ptx" "$build_dir/grouped-hot.ptx" <<'PY'
import pathlib, re, sys
text = pathlib.Path(sys.argv[1]).read_text()
entries = re.findall(r"(?ms)^\.visible \.entry (?:mark_adjacent_unique|reduce_adjacent_groups)[^\n]*\n.*?^\}\s*$", text)
if not entries: raise SystemExit("instantiated grouped reduction entries not found")
pathlib.Path(sys.argv[2]).write_text("\n".join(entries))
PY
for entry in mark_adjacent_unique reduce_adjacent_groups; do
  rg -q "\.entry $entry" "$build_dir/grouped-hot.ptx" || { printf '%s\n' "missing PTX entry: $entry" >&2; exit 1; }
done
if ! rg -q '\.reqntid 256, 1, 1' "$build_dir/grouped-hot.ptx" \
  || ! rg -q '(^|[[:space:]])ld\.' "$build_dir/grouped-hot.ptx" \
  || ! rg -q '(^|[[:space:]])st\.' "$build_dir/grouped-hot.ptx"; then
  printf '%s\n' 'grouped reduction PTX lost fixed launch or direct typed accesses' >&2
  exit 1
fi
if rg -n '(^|[[:space:]])(ld|st)\.local|(^|[[:space:]])call(\.|[[:space:]])|(^|[[:space:]])atom\.' "$build_dir/grouped-hot.ptx"; then
  printf '%s\n' 'grouped reduction PTX contains local traffic, out-of-line calls, or global atomics' >&2
  exit 1
fi
"$ptxas" -v -arch="$arch" "$build_dir/grouped-module.ptx" -o "$build_dir/grouped.cubin" 2>"$build_dir/resources.txt"
"$nvdisasm" "$build_dir/grouped.cubin" >"$build_dir/grouped.sass"
if ! rg -q 'LDG\.E|LD\.E' "$build_dir/grouped.sass" || ! rg -q 'STG\.E|ST\.E' "$build_dir/grouped.sass"; then
  printf '%s\n' 'grouped reduction SASS lost global loads or stores' >&2
  exit 1
fi
if rg -n 'LDL|STL|ATOM' "$build_dir/grouped.sass"; then
  printf '%s\n' 'grouped reduction module contains local-memory traffic or atomics' >&2
  exit 1
fi
rg 'mark_adjacent_unique|reduce_adjacent_groups|Used [0-9]+ registers|spill' "$build_dir/resources.txt" || true
printf '%s\n' 'Adjacent reduce-by-key CPU differential, contracts, fault, SM89, sanitizers, pinned CUB differential, and resource audit: PASS'
