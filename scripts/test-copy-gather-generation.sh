#!/usr/bin/env bash
set -euo pipefail

task_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$task_root"
source scripts/oxide-env.sh

readonly cccl_revision=571f2fc3bc53cd710e306ad43d58995c1fe4219f
cccl_root="${CCCL_ROOT:-$task_root/target/cccl-reference-$cccl_revision}"
if [[ ! -d "$cccl_root/.git" ]] || [[ "$(git -C "$cccl_root" rev-parse HEAD)" != "$cccl_revision" ]]; then
  printf '%s\n' "copy/gather/generation reference requires pinned CCCL $cccl_revision" >&2
  exit 1
fi
for source in \
  "$cccl_root/thrust/thrust/system/cuda/detail/copy.h" \
  "$cccl_root/thrust/thrust/system/cuda/detail/gather.h" \
  "$cccl_root/thrust/thrust/system/cuda/detail/fill.h" \
  "$cccl_root/thrust/thrust/system/detail/generic/sequence.h" \
  "$cccl_root/thrust/thrust/system/cuda/detail/tabulate.h"; do
  [[ -f "$source" ]] || { printf '%s\n' "missing pinned Thrust source: $source" >&2; exit 1; }
done

compute_sanitizer="$CUDA_TOOLKIT_PATH/compute-sanitizer/compute-sanitizer"
ptxas="$CUDA_HOME/bin/ptxas"
nvdisasm="$CUDA_HOME/bin/nvdisasm"
for tool in "$compute_sanitizer" "$ptxas" "$nvdisasm"; do
  [[ -x "$tool" ]] || { printf '%s\n' "required CUDA tool unavailable: $tool" >&2; exit 1; }
done

build_dir="$(mktemp -d "${TMPDIR:-/tmp}/rccl-copy-gather-generation.XXXXXX")"
cleanup() { rm -rf -- "$build_dir"; }
trap cleanup EXIT

cargo oxide build --arch "${RCCL_ARCH:-sm_89}" --features cuda-oxide-example -- \
  --release --package rccl-thrust --example copy_gather_generation
./target/release/examples/copy_gather_generation
"$compute_sanitizer" --tool memcheck --error-exitcode 97 \
  ./target/release/examples/copy_gather_generation
"$compute_sanitizer" --tool racecheck --error-exitcode 98 \
  ./target/release/examples/copy_gather_generation

./target/release/examples/copy_gather_generation --index-oob \
  >"$build_dir/oob.stdout" 2>"$build_dir/oob.stderr"
if ! rg -q 'gather index OOB surfaced:' "$build_dir/oob.stderr"; then
  printf '%s\n' 'out-of-bounds gather did not surface a CUDA execution fault' >&2
  exit 1
fi

cargo oxide build --arch "${RCCL_ARCH:-sm_89}" --features cuda-oxide-example -- \
  --release --package rccl-thrust --example copy_gather_generation_benchmark
python3 - target/release/examples/copy_gather_generation_benchmark "$build_dir/range-module.ptx" <<'PY'
import pathlib
import sys

image = pathlib.Path(sys.argv[1]).read_bytes()
marker = b"// Generated by LLVM NVPTX Back-End"
position = 0
while True:
    start = image.find(marker, position)
    if start < 0:
        raise SystemExit("embedded range PTX module not found")
    end = image.find(b"\0", start)
    if end < 0:
        raise SystemExit("unterminated embedded PTX module")
    module = image[start:end]
    if all(name in module for name in (b"range_transform_u32", b"range_fill_4b", b"range_generate_4b")):
        pathlib.Path(sys.argv[2]).write_bytes(module)
        break
    position = end + 1
PY
python3 - \
  "$build_dir/range-module.ptx" \
  "$build_dir/range-transform-hot.ptx" \
  "$build_dir/range-fill-hot.ptx" \
  "$build_dir/range-generate-hot.ptx" <<'PY'
import pathlib
import re
import sys

text = pathlib.Path(sys.argv[1]).read_text()
for stem, output in zip(
    ("range_transform_u32", "range_fill_4b", "range_generate_4b"),
    sys.argv[2:],
):
    entries = [
        match.group(0)
        for match in re.finditer(
            rf"(?ms)^\.visible \.entry {stem}[^\n]*\n.*?^\}}\s*$",
            text,
        )
    ]
    if not entries:
        raise SystemExit(f"instantiated {stem} entries not found")
    pathlib.Path(output).write_text("\n".join(entries))
PY
if ! rg -q '\.reqntid 256, 1, 1' "$build_dir/range-transform-hot.ptx" \
  || ! rg -q '(^|[[:space:]])ld\.b32' "$build_dir/range-transform-hot.ptx" \
  || ! rg -q '(^|[[:space:]])st\.b32' "$build_dir/range-transform-hot.ptx" \
  || ! rg -q 'trap;' "$build_dir/range-transform-hot.ptx"; then
  printf '%s\n' 'copy/gather PTX lost 256-thread launch, direct typed access, or gather OOB trap' >&2
  exit 1
fi
for ptx in "$build_dir/range-transform-hot.ptx" \
  "$build_dir/range-fill-hot.ptx" \
  "$build_dir/range-generate-hot.ptx"; do
  if rg -n '(^|[[:space:]])(ld|st)\.local|(^|[[:space:]])call(\.|[[:space:]])' "$ptx"; then
    printf '%s\n' "$ptx contains local-memory traffic or an out-of-line call" >&2
    exit 1
  fi
done
if ! rg -q '\.reqntid 256, 1, 1' "$build_dir/range-fill-hot.ptx" \
  || ! rg -q '(^|[[:space:]])st\.v2\.b32' "$build_dir/range-fill-hot.ptx"; then
  printf '%s\n' 'fill PTX lost the pinned SM89 256-thread, eight-item, 64-bit vector-store shape' >&2
  exit 1
fi
if ! rg -q '\.reqntid 256, 1, 1' "$build_dir/range-generate-hot.ptx" \
  || ! rg -q '(^|[[:space:]])st\.v4\.b32' "$build_dir/range-generate-hot.ptx"; then
  printf '%s\n' 'sequence PTX lost the pinned SM89 256-thread, eight-item, 128-bit vector-store shape' >&2
  exit 1
fi
"$ptxas" -v -arch="${RCCL_ARCH:-sm_89}" "$build_dir/range-module.ptx" \
  -o "$build_dir/range.cubin" 2>"$build_dir/ptxas-resources.txt"
"$nvdisasm" "$build_dir/range.cubin" >"$build_dir/range.sass"
if ! rg -q 'LD\.E' "$build_dir/range.sass" \
  || ! rg -q 'ST\.E' "$build_dir/range.sass" \
  || ! rg -q 'ST(G)?\.E\.64' "$build_dir/range.sass" \
  || ! rg -q 'ST(G)?\.E\.128' "$build_dir/range.sass"; then
  printf '%s\n' 'copy/gather/generation SASS lost direct access or pinned vector-store widths' >&2
  exit 1
fi
if rg -n 'LDL|STL' "$build_dir/range.sass"; then
  printf '%s\n' 'copy/gather/generation range module contains SASS local-memory traffic' >&2
  exit 1
fi
rg 'range_(transform_u32|fill_4b|generate_4b)|Used [0-9]+ registers|spill' "$build_dir/ptxas-resources.txt" || true

printf '%s\n' 'Copy/gather/generation correctness, boundary, fault, SM89, sanitizer, and resource audit: PASS'
