#!/usr/bin/env bash
set -euo pipefail

task_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$task_root"
source scripts/oxide-env.sh

readonly cuco_revision=1d538b6befc286ab450d9e27d7ffbc4f1415c641
readonly cccl_revision=571f2fc3bc53cd710e306ad43d58995c1fe4219f
cuco_root="${CUCO_ROOT:-$task_root/target/cuco-reference-$cuco_revision}"
cccl_root="${CCCL_ROOT:-$task_root/target/cccl-reference-$cccl_revision}"
for pinned in "$cuco_root/.git" "$cccl_root/.git"; do
  [[ -d "$pinned" ]] || { printf '%s\n' "missing pinned checkout: $pinned" >&2; exit 1; }
done
[[ "$(git -C "$cuco_root" rev-parse HEAD)" == "$cuco_revision" ]]
[[ "$(git -C "$cccl_root" rev-parse HEAD)" == "$cccl_revision" ]]

nvcc="$CUDA_HOME/bin/nvcc"
compute_sanitizer="$CUDA_TOOLKIT_PATH/compute-sanitizer/compute-sanitizer"
ptxas="$CUDA_HOME/bin/ptxas"
nvdisasm="$CUDA_HOME/bin/nvdisasm"
for tool in "$nvcc" "$compute_sanitizer" "$ptxas" "$nvdisasm"; do
  [[ -x "$tool" ]] || { printf '%s\n' "required CUDA tool unavailable: $tool" >&2; exit 1; }
done

build_dir="$(mktemp -d "${TMPDIR:-/tmp}/rccl-cuco-exact-set.XXXXXX")"
cleanup() { rm -rf -- "$build_dir"; }
trap cleanup EXIT

cargo test -p rccl-cuco exact_set::tests
cargo oxide build --arch "${RCCL_ARCH:-sm_89}" --features cuda-oxide-example -- \
  --release --package rccl-cuco --example exact_row_set
./target/release/examples/exact_row_set
"$compute_sanitizer" --tool memcheck --error-exitcode 97 ./target/release/examples/exact_row_set
"$compute_sanitizer" --tool racecheck --error-exitcode 98 ./target/release/examples/exact_row_set
"$compute_sanitizer" --tool synccheck --error-exitcode 99 ./target/release/examples/exact_row_set

cargo oxide build --arch "${RCCL_ARCH:-sm_89}" --features cuda-oxide-example -- \
  --release --package rccl-cuco --example exact_row_set_benchmark
python3 - target/release/examples/exact_row_set_benchmark "$build_dir/exact-set.ptx" <<'PY'
import pathlib
import sys
image = pathlib.Path(sys.argv[1]).read_bytes()
start = image.index(b"// Generated by LLVM NVPTX Back-End")
end = image.index(b"\0", start)
pathlib.Path(sys.argv[2]).write_bytes(image[start:end])
PY
python3 - "$build_dir/exact-set.ptx" "$build_dir/direct.ptx" <<'PY'
import pathlib
import re
import sys
text = pathlib.Path(sys.argv[1]).read_text()
match = re.search(r"(?ms)^\.visible \.entry exact_set_insert_prevalidated_direct_TID_.*?^\s*// -- End function", text)
if match is None:
    raise SystemExit("exact Row<2> insertion entry not found")
pathlib.Path(sys.argv[2]).write_text(match.group(0) + "\n")
PY
if ! rg -q '\.reqntid 128, 1, 1' "$build_dir/direct.ptx" \
  || ! rg -q 'atom\.relaxed\.gpu\.global\.cas\.b64' "$build_dir/direct.ptx" \
  || ! rg -q 'shfl\.sync' "$build_dir/direct.ptx"; then
  printf '%s\n' 'exact-set PTX lost its 128-thread, four-lane cooperative CAS insertion shape' >&2
  exit 1
fi
if rg -n '(atom|red)\..*\.sys|[ls]t?\.local|\bcall\b|\.visible \.func' "$build_dir/direct.ptx"; then
  printf '%s\n' 'exact-set Row<2> hot path contains a system atomic, local spill, or helper call' >&2
  exit 1
fi
"$ptxas" -v -arch="${RCCL_ARCH:-sm_89}" "$build_dir/exact-set.ptx" \
  -o "$build_dir/exact-set.cubin" 2> "$build_dir/ptxas-resources.txt"
"$nvdisasm" "$build_dir/exact-set.cubin" > "$build_dir/exact-set.sass"
if ! rg -q 'ATOM.*CAS' "$build_dir/exact-set.sass"; then
  printf '%s\n' 'exact-set SASS contains no 64-bit slot CAS' >&2
  exit 1
fi
if rg -n 'LDL|STL' "$build_dir/exact-set.sass"; then
  printf '%s\n' 'exact-set SASS contains local-memory traffic' >&2
  exit 1
fi
rg 'exact_set_insert_prevalidated_direct|Used [0-9]+ registers|spill' "$build_dir/ptxas-resources.txt" || true

"$nvcc" -std=c++20 -O3 --expt-extended-lambda -arch="${RCCL_ARCH:-sm_89}" \
  -I"$cuco_root/include" -I"$cccl_root/cub" -I"$cccl_root/thrust" \
  -I"$cccl_root/libcudacxx/include" benchmarks/cuco-exact-row-set-reference.cu \
  -o "$build_dir/cuco-exact-row-set-reference"
reference="$($build_dir/cuco-exact-row-set-reference 65536 0.5 3 contains)"
rust="$(target/release/examples/exact_row_set_benchmark --items 65536 --occupancy 0.5 --iterations 3 --operation contains)"
reference_capacity="$(sed -n 's/.*capacity=\([0-9]*\).*/\1/p' <<<"$reference")"
rust_capacity="$(sed -n 's/.*capacity=\([0-9]*\).*/\1/p' <<<"$rust")"
[[ -n "$reference_capacity" && "$reference_capacity" == "$rust_capacity" ]] || {
  printf '%s\n' "exact-set pinned capacity mismatch: cuco=$reference_capacity RCCL=$rust_capacity" >&2
  exit 1
}
printf '%s\n' "$reference" "$rust"
printf '%s\n' 'Pinned cuCollections exact HISA row-set correctness, collision-fault, sanitizer, differential, and PTX/SASS resource matrix: PASS'
